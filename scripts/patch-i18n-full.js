let totalApplied = 0, totalRequested = 0;
for (const [page, repls] of Object.entries(PATCHES)) {
  const file = path.join(PUBLIC, page);
  if (!fs.existsSync(file)) { console.log('  ↷ ' + page + ': no existeix'); continue; }
  let html = fs.readFileSync(file, 'utf8');
  let applied = 0;
  for (const [from, to] of repls) {
    totalRequested++;
    if (html.includes(from)) {
      // Saltar si ja té data-i18n al voltant (idempotent)
      const idx = html.indexOf(from);
      const window = html.substring(Math.max(0, idx - 40), idx + from.length);
      if (window.includes('data-i18n=') && from.length < 200) {
        // Possible que ja estigui patchat parcialment, comprovem el text
        if (html.indexOf(to.substring(0, 50)) === -1) {
          html = html.split(from).join(to);
          applied++; totalApplied++;
        }
      } else {
        html = html.split(from).join(to);
        applied++; totalApplied++;
      }
    }
  }
  fs.writeFileSync(file, html, 'utf8');
  console.log('  ✓ ' + page + ': ' + applied + '/' + repls.length + ' aplicats');
}
console.log('\nTotal: ' + totalApplied + '/' + totalRequested + ' substitucions');
